export function createEmptySeoMeta(arg: string | Partial<SeoMetaItem> = {}): SeoMetaItem {
  const isStringArg = typeof arg === 'string';
  const overrides: Partial<SeoMetaItem> = isStringArg
    ? {
        ogType: arg === 'blog' || arg === 'caseStudy' || arg === 'case_study' ? 'article' : 'website',
        schemaType:
          arg === 'blog'
            ? 'BlogPosting'
            : arg === 'service'
            ? 'Service'
            : arg === 'caseStudy' || arg === 'case_study'
            ? 'Article'
            : 'WebPage',
      }
    : arg;

  return {
    focusKeyword: '',
    secondaryKeywords: [],
    seoTitle: '',
    metaDescription: '',
    canonicalUrl: '',
    robotsIndex: 'index',
    robotsFollow: 'follow',
    robotsAdvanced: ['max-snippet:-1', 'max-image-preview:large', 'max-video-preview:-1'],
    ogTitle: '',
    ogDescription: '',
    ogImage: '',
    ogType: 'website',
    twitterCard: 'summary_large_image',
    twitterTitle: '',
    twitterDescription: '',
    twitterImage: '',
    breadcrumbTitle: '',
    schemaType: 'WebPage',
    faqSchemaEnabled: false,
    customFaqs: [],
    isCustomized: false,
    ...overrides,
  };
}

